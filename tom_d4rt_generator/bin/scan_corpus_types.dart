#!/usr/bin/env dart
/// Corpus type-combination scanner CLI.
///
/// Scans a directory of D4rt test scripts for the concrete type arguments used
/// in generic instantiations and emits an allowlist consumable by
/// `BridgeConfig.additionalRelaxerTypes`.
///
/// ```sh
/// dart run tom_d4rt_generator:scan_corpus_types \
///   --corpus tom_d4rt_flutter_ast/test/.../send_ast_via_http_scripts \
///   --output corpus_relaxer_allowlist.yaml
/// ```
library;

import 'dart:io';

import 'package:args/args.dart';
import 'package:tom_d4rt_generator/src/corpus_type_scanner.dart';

Future<void> main(List<String> args) async {
  final parser = ArgParser()
    ..addOption('corpus',
        abbr: 'c', help: 'Directory of D4rt scripts to scan (recursive).')
    ..addOption('output',
        abbr: 'o', help: 'Output file. Defaults to stdout.')
    ..addOption('format',
        abbr: 'f',
        allowed: ['yaml', 'text'],
        defaultsTo: 'yaml',
        help: 'Allowlist output format.')
    ..addFlag('help', abbr: 'h', negatable: false, help: 'Show usage.');

  final ArgResults parsed;
  try {
    parsed = parser.parse(args);
  } on FormatException catch (e) {
    stderr.writeln('Error: ${e.message}\n');
    stderr.writeln(parser.usage);
    exitCode = 64;
    return;
  }

  if (parsed['help'] as bool || parsed['corpus'] == null) {
    stdout.writeln('Scan a D4rt corpus for generic type-argument usage.\n');
    stdout.writeln(parser.usage);
    if (parsed['corpus'] == null && !(parsed['help'] as bool)) {
      exitCode = 64;
    }
    return;
  }

  final corpus = parsed['corpus'] as String;
  final scanner = const CorpusTypeScanner();

  final CorpusTypeScanResult result;
  try {
    result = scanner.scanDirectory(corpus);
  } on ArgumentError catch (e) {
    stderr.writeln('Error: ${e.message}');
    exitCode = 66;
    return;
  }

  final header = 'Auto-generated by tom_d4rt_generator:scan_corpus_types.\n'
      'Source corpus: $corpus\n'
      'Files scanned: ${result.filesScanned}, '
      'distinct type-args: ${result.distinctCount}.\n'
      'Feeds BridgeConfig.additionalRelaxerTypes when generateAllRelaxers: false.';

  final rendered = (parsed['format'] as String) == 'text'
      ? scanner.toTextAllowlist(result)
      : scanner.toYamlAllowlist(result, header: header);

  final output = parsed['output'] as String?;
  if (output == null) {
    stdout.write(rendered);
  } else {
    File(output).writeAsStringSync(rendered);
    stderr.writeln(
      'Wrote ${result.distinctCount} type-args from ${result.filesScanned} '
      'files → $output',
    );
  }

  if (result.readFailures.isNotEmpty) {
    stderr.writeln('Read failures (${result.readFailures.length}):');
    for (final f in result.readFailures) {
      stderr.writeln('  $f');
    }
  }
}
