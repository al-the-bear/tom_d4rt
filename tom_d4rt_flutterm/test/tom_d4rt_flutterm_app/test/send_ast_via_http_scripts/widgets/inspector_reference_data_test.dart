  print('Groups can be disposed via:');
  print('  WidgetInspectorService.disposeGroup(groupName)');
  print('Ensures inspector doesnt leak memory');

  // Test 10: Type checking
  print('\nTest 10: Special type handling');
  print('Types that skip WeakReference:');
  print('  - String');
  print('  - num (int, double)');
  print('  - bool');
  print('Reason: Not supported by WeakReference');

  print('\n' + '=' * 50);
  print('InspectorReferenceData test completed');

