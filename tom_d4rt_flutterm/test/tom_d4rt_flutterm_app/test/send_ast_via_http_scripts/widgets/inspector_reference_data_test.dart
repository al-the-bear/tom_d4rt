  print('Used for VM service protocol');

  // Test 7: Value access
  print('\nTest 7: Value getter');
  print('Object? get value =>');
  print('  _ref?.target ?? _value');
  print('');
  print('Returns null if object was GCd');
  print('Returns direct value for primitives');

  // Test 8: Usage context
  print('\nTest 8: Usage context');
  print('Created by WidgetInspectorService.toId()');
  print('Stored in object groups');
  print('Accessed via WidgetInspectorService.toObject()');

