  print('=' * 50);

  // === InspectorReferenceData class tests ===
  // InspectorReferenceData tracks object references in the widget
  // inspector. Does not hold object from garbage collection.

  // Test 1: Class purpose
  print('\nTest 1: Class purpose');
  print('Tracks object references for WidgetInspectorService');
  print('Uses WeakReference to avoid memory leaks');
  print('Annotated with @visibleForTesting');

  // Test 2: Constructor
  print('\nTest 2: Constructor');
  print('InspectorReferenceData(Object object, String id)');
  print('Stores object as WeakReference (for most types)');
  print('Direct storage for: String, num, bool');

  // Test 3: Properties
  print('\nTest 3: Properties');
  print('id: String - unique identifier for the object');
  print('count: int - number of times object referenced');
  print('value: Object? - the referenced object (via getter)');

  // Test 4: WeakReference behavior
  print('\nTest 4: WeakReference behavior');
  print('For complex objects:');
  print('  - Stored as WeakReference<Object>');
  print('  - Can be garbage collected');
  print('  - value getter returns ref.target');
  print('For String, num, bool:');
  print('  - Stored directly (not GC-able via WeakRef)');

  // Test 5: Reference counting
  print('\nTest 5: Reference counting');
  print('count property starts at 1');
  print('Incremented when object re-referenced');
  print('Used for lifecycle management');

  // Test 6: Id generation
