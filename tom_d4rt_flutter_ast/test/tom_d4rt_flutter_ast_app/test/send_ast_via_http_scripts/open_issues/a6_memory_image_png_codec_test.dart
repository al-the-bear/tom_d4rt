// Reproduces A.6 — MemoryImage(Uint8List) PNG codec rejection.
//
// Valid 1x1 PNG bytes handed to `MemoryImage` raise "Codec failed to produce an
// image" because the interpreter <-> ui.ImmutableBuffer bridge path corrupts the
// byte buffer. The framework error banner makes the harness record FE > 0.
//
// ignore_for_file: avoid_print

import 'dart:typed_data';

import 'package:flutter/material.dart';

// A valid 1x1 fully-transparent PNG (67 bytes).
final Uint8List _onePixelPng = Uint8List.fromList(<int>[
  0x89, 0x50, 0x4E, 0x47, 0x0D, 0x0A, 0x1A, 0x0A, //
  0x00, 0x00, 0x00, 0x0D, 0x49, 0x48, 0x44, 0x52, //
  0x00, 0x00, 0x00, 0x01, 0x00, 0x00, 0x00, 0x01, //
  0x08, 0x06, 0x00, 0x00, 0x00, 0x1F, 0x15, 0xC4, //
  0x89, 0x00, 0x00, 0x00, 0x0A, 0x49, 0x44, 0x41, //
  0x54, 0x78, 0x9C, 0x63, 0x00, 0x01, 0x00, 0x00, //
  0x05, 0x00, 0x01, 0x0D, 0x0A, 0x2D, 0xB4, 0x00, //
  0x00, 0x00, 0x00, 0x49, 0x45, 0x4E, 0x44, 0xAE, //
  0x42, 0x60, 0x82, //
]);

dynamic build(BuildContext context) {
  return Center(
    child: Image(
      image: MemoryImage(_onePixelPng),
      width: 1,
      height: 1,
    ),
  );
}
