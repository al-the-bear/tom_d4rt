// RUNNER BUCKET: guard — run_guard_tests.sh
// ghissues38 — native code calling a script override through a generated
// proxy receives the list type the override declares.
//
// Flutter 3.47's text field calls a configured
// `SpellCheckService.fetchSpellCheckSuggestions` itself. A script's override
// returns its `<SuggestionSpan>[]` as `List<Object?>`, and the proxy's
// `extractBridgedArg<List<SuggestionSpan>?>` refused it ("expected
// List<SuggestionSpan>?, got List<Object?>"), so
// `services/spell_check_service_test.dart` failed whenever the text field
// called the service during the test (found 2026-11-10 by ghissues34). This
// test makes that call from native code, as Flutter does. tom_d4rt_generator
// 1.62.0 rebuilds such a list with `D4.coerceList<E>`; the committed proxies
// carry the fix once they are regenerated with it (ghissues999), so until then
// the test skips itself.

import 'dart:io';

import 'package:flutter/material.dart';
import 'package:flutter/services.dart';
import 'package:flutter_test/flutter_test.dart';
import 'package:tom_d4rt_flutter/tom_d4rt_flutter.dart';

const _script = r'''
import 'package:flutter/material.dart';
import 'package:flutter/services.dart';

class _Mock extends SpellCheckService {
  @override
  Future<List<SuggestionSpan>?> fetchSpellCheckSuggestions(
    Locale locale,
    String text,
  ) async {
    await Future<void>.delayed(const Duration(milliseconds: 1));
    final List<SuggestionSpan> spans = <SuggestionSpan>[];
    final int idx = text.indexOf('teh');
    if (idx >= 0) {
      spans.add(SuggestionSpan(
        TextRange(start: idx, end: idx + 3),
        <String>['the', 'tea'],
      ));
    }
    return spans;
  }
}

SpellCheckConfiguration main() =>
    SpellCheckConfiguration(spellCheckService: _Mock());
''';

/// Whether the committed proxies were generated with the list conversion.
bool get _proxiesConvertLists => File(
  'lib/src/bridges/flutter_proxies.b.dart',
).readAsStringSync().contains('D4.coerceList<SuggestionSpan>');

void main() {
  test(
    'GHI38-F1: a proxied override returning a script list hands native code '
    'a List<SuggestionSpan> [2026-11-11]',
    () async {
      final config = SourceFlutterD4rt().execute<SpellCheckConfiguration>(
        _script,
      );
      final service = config.spellCheckService!;
      final Future<List<SuggestionSpan>?> future = service
          .fetchSpellCheckSuggestions(const Locale('en', 'US'), 'teh cat');
      final spans = await future;
      expect(spans, isA<List<SuggestionSpan>>());
      expect(spans!.single.range, const TextRange(start: 0, end: 3));
      expect(spans.single.suggestions, <String>['the', 'tea']);
    },
    skip: _proxiesConvertLists
        ? false
        : 'ghissues999: the committed proxies are generated by the published '
              'tom_d4rt_generator; the list conversion is in 1.62.0 '
              '(unpublished). Runs once the proxies are regenerated with it '
              '(tool/prepublish_overrides.dart --set does).',
  );
}
